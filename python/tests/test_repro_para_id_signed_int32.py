# FILE: tests/test_repro_para_id_signed_int32.py
"""
Repro tests for BUG_paraId_signed_int32_thread_collapse.md (B5, 2026-08-12,
Adeu 2.2.0 / 0db3cc2) — the CI half. The Word-verified half lives in
tests/test_live_word_para_id_signed_int32.py and needs Windows + Word.

`_generate_para_id` and `_generate_rsid` drew from `0 .. 0xFFFFFFFF`. Word
parses every `ST_LongHexNumber` as a SIGNED 32-bit integer and ECMA-376
requires the value to be greater than `0x00000000` and less than `0x80000000`,
so roughly HALF of every paraId Adeu minted was thrown away and regenerated by
Word on load — dangling every `w15:paraIdParent` that pointed at it and
dropping the reply out of its thread.

This is the third occurrence of one root cause:

    2026-08-11 B3   w16cid:durableId   comment anchor collapses to a point
    2026-08-12 B5   w14:paraId         reply threading collapses
    2026-08-12 B5   w:rsid*            no observed symptom; masked anyway

B3 was fixed as a POINT FIX to one attribute, and the reasoning behind it
("paraId and rsid are opaque 32-bit tokens with no such constraint") was
recorded as settled fact in two docstrings, AI_CONTEXT.md, and two tests that
went red when the bug was fixed. The point of this file is that it does not
care which attribute is the special one: `test_saved_package_carries_no_out_of
_range_long_hex_numbers` scans EVERY ST_LongHexNumber in the saved package, and
would have caught all three instances on the day they shipped.

Test-first: every assertion here fails on the pre-fix engine.
"""

import io
import random
import re

import pytest
from docx import Document

from adeu.models import ModifyText, ReplyComment
from adeu.redline.comments import CommentsManager
from adeu.redline.engine import RedlineEngine
from adeu.utils.long_hex_number import (
    ST_LONG_HEX_NUMBER_MAX,
    ST_LONG_HEX_NUMBER_MIN,
    is_word_readable_long_hex_number,
    to_long_hex_number,
)
from tests.utils import (
    assert_word_readable_ids,
    edge_of_range_randint,
    find_out_of_range_long_hex_numbers,
)

#: Word's rule for every ST_LongHexNumber, from ECMA-376: "shall be greater
#: than 0x00000000 and less than 0x80000000". Restated here as LITERALS on
#: purpose: the engine and the package scanner both derive their bounds from
#: adeu.utils.long_hex_number, so a wrong constant there would agree with
#: itself and pass. TestTheRuleItself is what stops that.
LEGAL_MIN = 0x00000001
LEGAL_MAX = 0x7FFFFFFF

#: 256 samples: a generator drawing from the full 32-bit range fails a
#: high-bit assertion with probability 1 - 2^-256, i.e. deterministically.
SAMPLES = 256

BODY = "The parties shall confer in good faith before moving to compel production."
TARGET = "confer in good faith"


def doc_stream(*paragraphs: str) -> io.BytesIO:
    doc = Document()
    for text in paragraphs or (BODY,):
        doc.add_paragraph(text)
    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf


def manager() -> CommentsManager:
    return CommentsManager(Document())


def threaded_package(reply_count: int = 2) -> bytes:
    """A saved package with one comment thread carrying `reply_count` replies."""
    engine = RedlineEngine(doc_stream(), author="Sarah Chen")
    engine.apply_edits([ModifyText(target_text=TARGET, new_text=TARGET, comment="Root note.")])
    root_id = next(iter(engine.comments_manager.extract_comments_data()))
    engine.author = "Adeu AI"
    for i in range(reply_count):
        engine.apply_review_actions([ReplyComment(target_id=f"Com:{root_id}", text=f"Reply {i}.")])
    return engine.save_to_stream().getvalue()


def offenders(values, label: str) -> str:
    bad = [v for v in values if not LEGAL_MIN <= int(v, 16) <= LEGAL_MAX]
    return (
        f"{len(bad)}/{len(values)} generated {label}s are outside "
        f"(0x00000000, 0x80000000) — e.g. {bad[:4]}. Word parses ST_LongHexNumber as a SIGNED "
        "32-bit integer: it discards these on load and regenerates them, breaking every "
        "reference that pointed at them."
    )


