class TestSavedPackageIds:
    def test_saved_package_carries_no_out_of_range_long_hex_numbers(self):
        """
        Attribute-agnostic, end-to-end: scan every `.xml` part of a saved
        package for every attribute typed `ST_LongHexNumber` and require all of
        them to be in range. Prefer this to three attribute-specific tests — it
        is what turns a third point fix into a closed class.
        """
        assert_word_readable_ids(threaded_package(), context="threaded document: ")

    @pytest.mark.parametrize("high", [True, False], ids=["top-of-range", "bottom-of-range"])
    def test_no_call_site_can_reach_an_unmasked_generator(self, high, monkeypatch):
        """
        `random.randint` is pinned to one END of whatever range each generator
        asks for — always a value that call could legitimately have returned.
        A generator over `0 .. 0xFFFFFFFF` then mints `FFFFFFFF…` (high) or
        `00000000…` (low); a masked one mints `7FFFFFFF…` / `00000001…`.

        Because the substitution is global, this covers every mint site that
        `add_comment` can reach — not just the ones a reviewer remembered — and
        it fails deterministically rather than 50% of the time.
        """
        monkeypatch.setattr(random, "randint", edge_of_range_randint(high=high))
        assert_word_readable_ids(threaded_package(reply_count=3), context=f"{'high' if high else 'low'} RNG: ")

    @pytest.mark.parametrize(
        "attribute",
        ["w14:paraId", "w14:textId", "w15:paraIdParent", "w16cid:durableId", "w:rsidR", "w:rsidSect"],
    )
    @pytest.mark.parametrize("value", ["80000000", "FFFFFFFF", "00000000"])
    def test_the_package_scanner_detects_every_shape_of_bad_id(self, attribute, value):
        """
        Guards the guard. A scanner that silently matched nothing would make
        every test above vacuous, and a bug class that hides behind a check
        which never fires is exactly what this file exists to stop. Built from
        a synthetic package so it measures the SCANNER, not the engine.
        """
        package = self._synthetic_package(f'<w:p {attribute}="{value}"/>')
        assert [(attr, val) for _part, attr, val in find_out_of_range_long_hex_numbers(package)] == [(attribute, value)]

    @pytest.mark.parametrize("value", ["00000001", "7FFFFFFF", "12345678"])
    def test_the_package_scanner_accepts_legal_ids(self, value):
        package = self._synthetic_package(f'<w:p w14:paraId="{value}"/>')
        assert find_out_of_range_long_hex_numbers(package) == []

    def test_the_package_scanner_reads_the_w_rsids_element_form(self):
        """`<w:rsid w:val="…"/>` in settings.xml carries the same type in an
        element rather than on the paragraph. Adeu does not write it today;
        the scanner covers it so that the day something does, it is checked."""
        package = self._synthetic_package('<w:rsids><w:rsidRoot w:val="C0000001"/></w:rsids>')
        assert [attr for _part, attr, _v in find_out_of_range_long_hex_numbers(package)] == ["w:rsidRoot/@w:val"]

    @staticmethod
    def _synthetic_package(fragment: str) -> bytes:
        import zipfile

        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w") as archive:
            archive.writestr("word/document.xml", f"<w:document>{fragment}</w:document>")
            # Non-XML parts must be skipped, not decoded as text.
            archive.writestr("word/media/image1.png", b"\x89PNG\r\n\x1a\n\xff\xff\xff\xff")
        return buffer.getvalue()

    def test_a_document_with_no_comments_is_already_clean(self):
        """
        Baseline: the ids Adeu inherits from python-docx's template (rsids in
        settings/styles, the body paragraph ids) are all in range, so a failure
        of the scan above can only be something Adeu minted.
        """
        engine = RedlineEngine(doc_stream(), author="Adeu AI")
        engine.apply_edits([ModifyText(target_text="good faith", new_text="good faith and candor")])
        assert_word_readable_ids(engine.save_to_stream().getvalue(), context="no comments: ")


