POISON_FOLDED = "52AEAE20"


def repack(package: bytes, rewrite) -> bytes:
    """Rebuild a DOCX with `rewrite` applied to the text of every XML part."""
    out = io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(package)) as src:
        with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
            for item in src.infolist():
                data = src.read(item.filename)
                if item.filename.endswith(".xml"):
                    data = rewrite(item.filename, data.decode("utf-8")).encode("utf-8")
                dst.writestr(item, data)
    return out.getvalue()


def poison(package: bytes, replacements: Dict[str, str]) -> bytes:
    """Rewrite ST_LongHexNumber values across every part, references included.

    This is exactly what produced the demo document: a fixture builder that
    rewrote the ids in a Word-authored package, masked `w16cid:durableId`
    because B3 had taught it to, and left `w14:paraId` alone because the note
    B3 left behind said paraId was unconstrained. The result validates against
    the schema, opens without complaint, and silently loses its thread.
    """

    def rewrite(_name: str, text: str) -> str:
        for old, new in replacements.items():
            text = text.replace(f'"{old}"', f'"{new}"')
        return text

    return repack(package, rewrite)


def part_text(package: bytes, stem: str) -> str:
    """The text of `word/<stem>.xml`, tolerating python-docx's part numbering.

    Word writes `word/comments.xml`; python-docx writes `word/comments1.xml`
    for the same part. Matching the stem exactly (rather than by substring)
    also keeps `comments` from selecting `commentsExtended`.
    """
    pattern = re.compile(rf"^word/{stem}\d*\.xml$")
    with zipfile.ZipFile(io.BytesIO(package)) as archive:
        name = next((n for n in archive.namelist() if pattern.match(n)), None)
        assert name, f"no word/{stem}.xml part in {archive.namelist()}"
        return archive.read(name).decode("utf-8")


def comment_ex_entries(package: bytes):
    """`[(paraId, paraIdParent or None)]` from commentsExtended, in order."""
    xml = part_text(package, "commentsExtended")
    return [
        (m.group("id"), m.group("parent"))
        for m in re.finditer(
            r'<w15:commentEx\b(?=[^>]*\bw15:paraId="(?P<id>[0-9A-Fa-f]{1,8})")'
            r'(?=(?:[^>]*\bw15:paraIdParent="(?P<parent>[0-9A-Fa-f]{1,8})")?)[^>]*>',
            xml,
        )
    ]


def root_para_id(package: bytes) -> str:
    """The one commentEx with no parent — the thread root."""
    roots = [para_id for para_id, parent in comment_ex_entries(package) if not parent]
    assert len(roots) == 1, f"fixture precondition: expected exactly one thread root, got {roots}"
    return roots[0]


def thread_of(package: bytes) -> Dict[str, Optional[str]]:
    return dict(comment_ex_entries(package))


def para_ids_in(package: bytes, part: str = "comments"):
    return re.findall(r'w14:paraId="([0-9A-Fa-f]{1,8})"', part_text(package, part))


def reply_to_root(package: bytes, text: str = "Addressed.", author: str = "Adeu AI") -> bytes:
    """Reply to whichever comment owns the thread root, and save."""
    engine = RedlineEngine(io.BytesIO(package), author=author)
    comments = engine.comments_manager.extract_comments_data()
    applied, skipped, _ = engine.apply_review_actions(
        [ReplyComment(target_id=f"Com:{next(iter(comments))}", text=text)]
    )
    assert (applied, skipped) == (1, 0), "the reply did not apply at all"
    return engine.save_to_stream().getvalue()


def offenders(values, label: str) -> str:
    bad = [v for v in values if not LEGAL_MIN <= int(v, 16) <= LEGAL_MAX]
    return (
        f"{len(bad)}/{len(values)} generated {label}s are outside "
        f"(0x00000000, 0x80000000) — e.g. {bad[:4]}. Word parses ST_LongHexNumber as a SIGNED "
        "32-bit integer: it discards these on load and regenerates them, breaking every "
        "reference that pointed at them."
    )


