class TestAnInheritedOutOfRangeIdIsRepaired:
    """
    B6 (2026-08-12, western-district demo). B5 fixed every id Adeu MINTS, and
    the two tests above prove it: both build their parent with the fixed
    engine, so the thread root is always already legal. Neither covers a parent
    that arrives with an id Word will throw away.

    That is the case that shipped. Sarah Chen's comment came in carrying
    `w14:paraId="D2AEAE20"`, `_adopt_into_modern_comments` found a paraId and
    reused it verbatim, and the reply's `w15:paraIdParent` was written to point
    at a value Word discards on load. Every check passed on the way out — the
    reply IS parented, `CommentThreadingError` correctly did not fire, and the
    package scanner was only ever run against ids the engine minted.

    Adeu cannot mint its way out of an inherited id. It has to repair it, and
    repair it everywhere it is referenced, or the repair de-threads the replies
    that were already pointing at it.
    """

    def test_a_reply_threads_onto_a_parent_whose_para_id_word_would_discard(self):
        """The demo, reduced: one inherited high-bit paraId, one reply."""
        base = threaded_package(reply_count=0)
        package = poison(base, {root_para_id(base): POISON})
        assert POISON in part_text(package, "comments"), "fixture precondition: the parent is not poisoned"

        saved = reply_to_root(package)

        assert_word_readable_ids(saved, context="inherited parent paraId: ")
        entries = thread_of(saved)
        replies = {para_id: parent for para_id, parent in entries.items() if parent}
        assert len(replies) == 1, f"expected exactly one reply, got {entries}"
        parent = next(iter(replies.values()))
        assert parent in entries and not entries[parent], (
            f"the reply points at {parent}, which is not a thread root in {entries}. Word renders "
            "it as a second top-level comment: right author, right text, wrong place."
        )

    def test_the_repaired_root_keeps_the_replies_that_already_pointed_at_it(self):
        """
        The repair's own failure mode. Rewriting the root's paraId without
        rewriting the `w15:paraIdParent`s that referenced it turns one broken
        thread into N broken threads — strictly worse than doing nothing.
        """
        base = threaded_package(reply_count=2)
        package = poison(base, {root_para_id(base): POISON})

        saved = reply_to_root(package, text="Third reply.")

        entries = thread_of(saved)
        roots = [para_id for para_id, parent in entries.items() if not parent]
        parents = {parent for parent in entries.values() if parent}
        assert len(roots) == 1, f"the repair split the thread into {len(roots)} roots: {entries}"
        assert parents == set(roots), f"replies point at {parents}, thread root is {roots}: {entries}"
        assert len(entries) == 4, f"expected root + 3 replies, got {entries}"

    def test_the_repaired_para_id_is_identical_in_all_three_comment_parts(self):
        """
        Word consults comments.xml, commentsExtended AND commentsIds. A paraId
        repaired in one and left stale in another drops the comment out of the
        modern-comments path entirely — the same end state as not repairing it.
        """
        base = threaded_package(reply_count=1)
        package = poison(base, {root_para_id(base): POISON})

        saved = reply_to_root(package)

        for part in ("comments", "commentsExtended", "commentsIds"):
            text = part_text(saved, part)
            assert POISON not in text, f"{part} still carries the discarded paraId {POISON}"
        root = root_para_id(saved)
        assert f'w14:paraId="{root}"' in part_text(saved, "comments"), "root missing from comments.xml"
        assert f'w16cid:paraId="{root}"' in part_text(saved, "commentsIds"), "root missing from commentsIds"

    def test_the_repair_folds_rather_than_reinvents(self):
        """
        `D2AEAE20 -> 52AEAE20`: clear the top bit, which is what Word does to
        the value anyway. Pinned because it is the exact substitution that was
        verified in Word against the demo document, and because a deterministic
        repair keeps a re-run of the same document producing the same ids.
        """
        base = threaded_package(reply_count=0)
        package = poison(base, {root_para_id(base): POISON})

        saved = reply_to_root(package)

        assert root_para_id(saved) == POISON_FOLDED, (
            f"expected the root to fold to {POISON_FOLDED}, got {root_para_id(saved)}"
        )

    def test_inherited_out_of_range_rsids_are_repaired_too(self):
        """
        The demo document carried `w:rsidR/@w:rsidRDefault/@w:rsidP =
        AD3412F6` alongside the bad paraId. Word renumbers a PART, not an
        attribute, so leaving a bad rsid in comments.xml re-arms the same
        renumbering pass that de-threads the reply.
        """
        base = threaded_package(reply_count=0)
        package = poison(base, {root_para_id(base): POISON, **{r: "AD3412F6" for r in _rsids_of(base)}})
        assert "AD3412F6" in part_text(package, "comments"), "fixture precondition: no poisoned rsid"

        saved = reply_to_root(package)

        assert_word_readable_ids(saved, context="inherited rsid: ")
        assert "AD3412F6" not in part_text(saved, "comments")

    def test_the_repair_leaves_the_comment_body_author_and_date_untouched(self):
        """An id repair that edits the record it identifies is not a repair."""
        base = threaded_package(reply_count=0)
        package = poison(base, {root_para_id(base): POISON})

        saved = reply_to_root(package)

        comments = RedlineEngine(io.BytesIO(saved), author="x").comments_manager.extract_comments_data()
        root = next(c for c in comments.values() if c["text"] == "Root note.")
        original = next(
            c for c in RedlineEngine(io.BytesIO(package), author="x").comments_manager.extract_comments_data().values()
        )
        assert (root["author"], root["text"]) == (original["author"], original["text"])

    def test_a_package_whose_ids_are_already_legal_is_left_alone(self):
        """
        The repair must be a no-op on a healthy document. A pass that re-mints
        unconditionally would churn every paraId on every save and invalidate
        every `{#cell:<paraId>}` anchor the caller is holding — the exact
        damage it exists to prevent.
        """
        base = threaded_package(reply_count=1)
        before = set(para_ids_in(base))

        saved = reply_to_root(base)

        assert before <= set(para_ids_in(saved)), (
            f"the repair re-minted ids that were already legal: {before - set(para_ids_in(saved))}"
        )

    def test_a_reply_to_a_reply_still_flattens_onto_the_repaired_root(self):
        """
        Modern Word has no nesting: a reply to a reply points at the thread
        ROOT. That lookup runs through the poisoned value, so it has to see the
        repaired one.
        """
        base = threaded_package(reply_count=1)
        package = poison(base, {root_para_id(base): POISON})

        engine = RedlineEngine(io.BytesIO(package), author="Adeu AI")
        comments = engine.comments_manager.extract_comments_data()
        reply_id = list(comments)[-1]
        applied, skipped, _ = engine.apply_review_actions(
            [ReplyComment(target_id=f"Com:{reply_id}", text="Reply to the reply.")]
        )
        assert (applied, skipped) == (1, 0)
        saved = engine.save_to_stream().getvalue()

        entries = thread_of(saved)
        roots = [para_id for para_id, parent in entries.items() if not parent]
        assert len(roots) == 1, f"reply-to-reply created a second root: {entries}"
        assert all(parent == roots[0] for parent in entries.values() if parent), entries

    def test_the_engine_repairs_what_the_demo_document_actually_shipped(self):
        """
        End to end on the real shape: parent paraId AND its registrations in
        commentsExtended / commentsIds all poisoned together, which is how a
        fixture builder that rewrites ids leaves a document.
        """
        base = threaded_package(reply_count=0)
        package = poison(base, {root_para_id(base): POISON})
        assert [(a, v) for _p, a, v in find_out_of_range_long_hex_numbers(package)] == [
            ("w14:paraId", POISON),
            ("w15:paraId", POISON),
            ("w16cid:paraId", POISON),
        ], "fixture precondition: not the demo's shape"

        assert find_out_of_range_long_hex_numbers(reply_to_root(package)) == []


def _rsids_of(package: bytes):
    return set(re.findall(r'w:rsidR="([0-9A-Fa-f]{1,8})"', part_text(package, "comments")))


