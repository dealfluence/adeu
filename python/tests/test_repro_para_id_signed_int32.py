class TestThreadingIdsResolve:
    W15 = "http://schemas.microsoft.com/office/word/2012/wordml"

    @staticmethod
    def _comment_ex(package: bytes):
        import zipfile

        with zipfile.ZipFile(io.BytesIO(package)) as archive:
            name = next(n for n in archive.namelist() if "commentsExtended" in n)
            xml = archive.read(name).decode("utf-8")
        return re.findall(r'w15:paraId="([0-9A-Fa-f]{8})"(?:\s+w15:paraIdParent="([0-9A-Fa-f]{8})")?', xml)

    def test_every_reply_points_at_an_in_range_parent_para_id(self):
        """
        64 independent threads, so a generator that is right half the time
        cannot pass by luck (2^-64). B1 already guarantees a reply carries
        `w15:paraIdParent`; what this adds is that the value it points AT is
        one Word will still recognise after load. A reply can be perfectly
        parented in the XML and still not thread.
        """
        dangling = []
        for _ in range(64):
            entries = self._comment_ex(threaded_package(reply_count=1))
            roots = {para_id for para_id, parent in entries if not parent}
            for para_id, parent in entries:
                if not parent:
                    continue
                assert parent in roots, f"reply {para_id} points at unknown parent {parent}"
                if not LEGAL_MIN <= int(parent, 16) <= LEGAL_MAX:
                    dangling.append(parent)
                if not LEGAL_MIN <= int(para_id, 16) <= LEGAL_MAX:
                    dangling.append(para_id)

        assert not dangling, (
            f"{len(dangling)}/64 threads reference a paraId Word will discard: {dangling[:4]}. "
            "The reply IS parented — process_batch reports success and B1's CommentThreadingError "
            "correctly does not fire — it just stops being a reply the moment Word opens the file."
        )

    def test_a_legacy_parent_adopted_for_threading_gets_an_in_range_para_id(self, monkeypatch):
        """
        The second mint site: a parent comment with no `w14:paraId` (pre-2013
        Word, or any generator without the modern-comments extensions) has one
        minted for it so the reply can thread (`_adopt_into_modern_comments`).
        That id is the thread ROOT, the worst place for a bad one — an
        out-of-range root takes every reply in the thread down with it.
        """
        engine = RedlineEngine(doc_stream(), author="Sarah Chen")
        engine.apply_edits([ModifyText(target_text=TARGET, new_text=TARGET, comment="Legacy note.")])
        source = engine.save_to_stream()

        # Strip the paraId to produce the legacy comment shape.
        from docx.oxml.ns import qn

        source.seek(0)
        doc = Document(io.BytesIO(source.getvalue()))
        comments_part = next(
            p for p in doc.part.package.parts if p.content_type.endswith("wordprocessingml.comments+xml")
        )
        from docx.opc.part import XmlPart
        from docx.oxml import parse_xml

        element = parse_xml(comments_part.blob)
        stripped = 0
        for comment in element.findall(qn("w:comment")):
            for para in comment.findall(qn("w:p")):
                if para.get(qn("w14:paraId")) is not None:
                    del para.attrib[qn("w14:paraId")]
                    stripped += 1
        assert stripped, "fixture precondition: nothing to strip"

        replacement = XmlPart(comments_part.partname, comments_part.content_type, element, comments_part.package)
        package = comments_part.package
        package.parts[package.parts.index(comments_part)] = replacement
        for rel in doc.part.rels.values():
            if not rel.is_external and rel.target_part is comments_part:
                rel._target = replacement
        legacy = io.BytesIO()
        doc.save(legacy)
        legacy.seek(0)

        monkeypatch.setattr(random, "randint", edge_of_range_randint(high=True))
        engine = RedlineEngine(legacy, author="Adeu AI")
        parent_id = next(iter(engine.comments_manager.extract_comments_data()))
        applied, skipped, _ = engine.apply_review_actions(
            [ReplyComment(target_id=f"Com:{parent_id}", text="Addressed.")]
        )
        assert (applied, skipped) == (1, 0), "the reply did not apply at all"

        assert_word_readable_ids(engine.save_to_stream().getvalue(), context="adopted legacy parent: ")
