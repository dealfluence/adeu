#: Word's rule for every ST_LongHexNumber, from ECMA-376: "shall be greater
#: than 0x00000000 and less than 0x80000000". Restated here as LITERALS on
#: purpose: the engine and the package scanner both derive their bounds from
#: adeu.utils.long_hex_number, so a wrong constant there would agree with
#: itself and pass. TestTheRuleItself is what stops that.
LEGAL_MIN = 0x00000001
LEGAL_MAX = 0x7FFFFFFF

#: 256 samples: a generator drawing from the full 32-bit range fails a
#: high-bit assertion with probability 1 - 2^-256, i.e. deterministically.
SAMPLES = 256

BODY = "The parties shall confer in good faith before moving to compel production."
TARGET = "confer in good faith"


def doc_stream(*paragraphs: str) -> io.BytesIO:
    doc = Document()
    for text in paragraphs or (BODY,):
        doc.add_paragraph(text)
    buf = io.BytesIO()
    doc.save(buf)
    buf.seek(0)
    return buf


def manager() -> CommentsManager:
    return CommentsManager(Document())


def threaded_package(reply_count: int = 2) -> bytes:
    """A saved package with one comment thread carrying `reply_count` replies."""
    engine = RedlineEngine(doc_stream(), author="Sarah Chen")
    engine.apply_edits([ModifyText(target_text=TARGET, new_text=TARGET, comment="Root note.")])
    root_id = next(iter(engine.comments_manager.extract_comments_data()))
    engine.author = "Adeu AI"
    for i in range(reply_count):
        engine.apply_review_actions([ReplyComment(target_id=f"Com:{root_id}", text=f"Reply {i}.")])
    return engine.save_to_stream().getvalue()


