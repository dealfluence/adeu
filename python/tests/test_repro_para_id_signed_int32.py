class TestParaIdUniqueness:
    """
    [MS-DOCX] 2.6.2.4: `w14:paraId` "specifies an identifier for a paragraph
    that is UNIQUE WITHIN THE DOCUMENT PART". Like the range rule, it is prose
    rather than schema, so nothing rejects a duplicate.

    It becomes load-bearing the moment ids are repaired rather than minted:
    folding clears the top bit, and `D2AEAE20` and `52AEAE20` fold to the SAME
    value. A repair that ignores uniqueness turns a dangling `paraIdParent`
    into an ambiguous one, which is not an improvement.
    """

    def test_a_freshly_written_thread_has_no_duplicate_para_ids(self):
        assert find_duplicate_para_ids(threaded_package(reply_count=3)) == []

    def test_repairing_never_collides_with_a_para_id_already_in_the_part(self):
        """
        The collision is constructed, not hoped for: the document already
        contains `52AEAE20`, which is exactly what `D2AEAE20` folds to.
        """
        engine = RedlineEngine(doc_stream(), author="Sarah Chen")
        engine.apply_edits(
            [
                ModifyText(target_text=TARGET, new_text=TARGET, comment="Root note."),
                ModifyText(target_text="production", new_text="production", comment="Second thread."),
            ]
        )
        base = engine.save_to_stream().getvalue()
        first, second = para_ids_in(base)[:2]
        package = poison(base, {first: POISON, second: POISON_FOLDED})
        assert POISON_FOLDED in part_text(package, "comments"), "fixture precondition: no collision to hit"

        saved = reply_to_root_of(package, POISON)

        assert find_duplicate_para_ids(saved) == [], (
            "the repair folded onto a paraId the part was already using; "
            "[MS-DOCX] requires paraId to be unique within the part"
        )
        assert_word_readable_ids(saved, context="collision repair: ")

    def test_the_duplicate_scanner_detects_a_collision(self):
        """Guards the guard: a scanner that never fires makes the above vacuous."""
        base = threaded_package(reply_count=1)
        ids = para_ids_in(base)
        collided = poison(base, {ids[1]: ids[0]})
        assert [(attr, value) for _part, attr, value in find_duplicate_para_ids(collided)] == [("w14:paraId", ids[0])]


def reply_to_root_of(package: bytes, para_id: str) -> bytes:
    """Reply to the comment whose paragraph carries `para_id`."""
    engine = RedlineEngine(io.BytesIO(package), author="Adeu AI")
    xml = part_text(package, "comments")
    match = re.search(
        r'<w:comment\b[^>]*\bw:id="(\d+)"(?:(?!</w:comment>).)*?w14:paraId="' + para_id + '"',
        xml,
        re.DOTALL,
    )
    assert match, f"no comment carries paraId {para_id}"
    applied, skipped, _ = engine.apply_review_actions(
        [ReplyComment(target_id=f"Com:{match.group(1)}", text="Addressed.")]
    )
    assert (applied, skipped) == (1, 0)
    return engine.save_to_stream().getvalue()


class TestTextIdAccompaniesParaId:
    """
    [MS-DOCX] 2.6.2.6: `w14:textId` carries the same range rule AND "any
    element having this attribute MUST also have the paraId attribute".

    Adeu writes `w14:textId` on every comment paragraph it creates, so the
    pairing is a real obligation, and it constrains the repair: stripping or
    renaming a paraId while leaving its textId behind produces an element that
    violates the spec even though every id on it is in range.
    """

    def test_every_text_id_travels_with_a_para_id(self):
        assert find_text_ids_without_para_id(threaded_package(reply_count=2)) == []

    def test_the_pairing_survives_repairing_an_inherited_para_id(self):
        base = threaded_package(reply_count=1)
        package = poison(base, {root_para_id(base): POISON})
        assert find_text_ids_without_para_id(reply_to_root(package)) == []

    def test_the_text_id_adeu_writes_is_in_range(self):
        """
        `w14:textId` is an ST_LongHexNumber like every other id here, and the
        package scanner already covers it. Stated separately because it is the
        one Adeu writes as a literal rather than from the generator.
        """
        for value in re.findall(r'w14:textId="([0-9A-Fa-f]{1,8})"', part_text(threaded_package(), "comments")):
            assert is_word_readable_long_hex_number(value), f"textId {value} is outside the legal range"

    def test_the_pairing_scanner_detects_a_lone_text_id(self):
        base = threaded_package(reply_count=0)
        orphaned = repack(base, lambda name, text: re.sub(r'\s*w14:paraId="[0-9A-Fa-f]{1,8}"', "", text, count=1))
        assert find_text_ids_without_para_id(orphaned), "the scanner missed a textId with no paraId"
