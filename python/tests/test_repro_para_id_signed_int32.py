class TestGeneratorRanges:
    """
    Every `ST_LongHexNumber` Adeu mints must land in `(0x00000000,
    0x80000000)`. Parametrised over all three generators deliberately: the way
    this bug shipped was a fix applied to exactly one of them, so a per-
    attribute test is how the class survives.
    """

    @pytest.mark.parametrize("generator", ["_generate_para_id", "_generate_rsid", "_generate_durable_id"])
    def test_generated_ids_are_valid_st_long_hex_numbers(self, generator):
        mint = getattr(manager(), generator)
        values = [mint() for _ in range(SAMPLES)]
        assert all(LEGAL_MIN <= int(v, 16) <= LEGAL_MAX for v in values), offenders(
            values, generator.removeprefix("_generate_")
        )

    @pytest.mark.parametrize("generator", ["_generate_para_id", "_generate_rsid", "_generate_durable_id"])
    def test_generated_ids_are_eight_upper_case_hex_digits(self, generator):
        mint = getattr(manager(), generator)
        for _ in range(64):
            value = mint()
            assert re.fullmatch(r"[0-9A-F]{8}", value), (
                f"{generator} produced {value!r}, which is not an 8-digit upper-case ST_LongHexNumber"
            )

    @pytest.mark.parametrize("generator", ["_generate_para_id", "_generate_rsid", "_generate_durable_id"])
    def test_no_generator_can_return_zero(self, generator, monkeypatch):
        """
        `00000000` is forbidden as explicitly as the high half, and it is the
        one value in this class Word does NOT paper over: a comment paragraph
        with `w14:paraId="00000000"` makes Word declare the file corrupted and
        refuse to open it (Word-verified). `randint(0, …)` can return it.
        """
        # The smallest value this generator can possibly emit.
        monkeypatch.setattr(random, "randint", lambda a, b: a)
        assert getattr(manager(), generator)() != "00000000", (
            f"{generator} can mint 00000000. Word rejects the whole package: the generator must start at 1, not 0."
        )

    def test_every_generator_draws_from_the_same_range(self, monkeypatch):
        """
        The class-level guard. B3 was fixed by giving ONE attribute its own
        masked generator and writing down that the others did not need it —
        which is precisely how B5 shipped. Pinning that the generators agree
        makes 'narrow one, leave the others' fail at the next attempt.
        """
        names = ("_generate_para_id", "_generate_rsid", "_generate_durable_id")
        for edge, expected in ((lambda a, b: a, "00000001"), (lambda a, b: b, "7FFFFFFF")):
            monkeypatch.setattr(random, "randint", edge)
            mgr = manager()
            bounds = {name: getattr(mgr, name)() for name in names}
            assert set(bounds.values()) == {expected}, (
                f"the generators do not share a bound: {bounds}. Every ST_LongHexNumber goes "
                "through one generator; there is no attribute for which the high half is safe."
            )


