# The rule itself
# ---------------------------------------------------------------------------


class TestTheRuleItself:
    """
    `adeu.utils.long_hex_number` is the single definition of "an id Word will
    keep": the generators mint against it and the package scanner audits
    against it. That is the right structure, and it has one failure mode — a
    wrong constant would be consistent with itself everywhere. Everything here
    checks it against LITERALS taken from the spec text, not against itself.
    """

    def test_the_bounds_are_the_ones_ecma_376_states(self):
        assert (ST_LONG_HEX_NUMBER_MIN, ST_LONG_HEX_NUMBER_MAX) == (LEGAL_MIN, LEGAL_MAX), (
            "ECMA-376: the value shall be greater than 0x00000000 and less than 0x80000000"
        )

    @pytest.mark.parametrize(
        "value, readable, why",
        [
            ("00000000", False, "forbidden: Word rejects the whole package"),
            ("00000001", True, "smallest legal value"),
            ("12345678", True, "ordinary value"),
            ("7FFFFFFF", True, "largest legal value"),
            ("80000000", False, "smallest illegal value — exactly one greater"),
            ("D2AEAE20", False, "the id from the field report that collapsed the thread"),
            ("FFFFFFFF", False, "all bits set"),
            ("", False, "not a value at all"),
            ("1234567", True, "short forms are legal; Word writes them padded"),
            ("123456789", False, "too long for xsd:hexBinary length 4"),
            ("ZZZZZZZZ", False, "not hexadecimal"),
        ],
    )
    def test_the_predicate_agrees_with_the_specification(self, value, readable, why):
        assert is_word_readable_long_hex_number(value) is readable, why

    @pytest.mark.parametrize(
        "value, folded",
        [
            (0x00000000, "00000001"),  # 0 is forbidden, so it cannot be the identity
            (0x00000001, "00000001"),
            (0x7FFFFFFF, "7FFFFFFF"),
            (0x80000000, "00000001"),  # masks to 0, which is forbidden -> MIN
            (0x80000001, "00000001"),
            (0xFFFFFFFF, "7FFFFFFF"),
            (0xFC855CFC, "7C855CFC"),  # the first id Node's cell anchor derived
        ],
    )
    def test_folding_a_derived_value_lands_in_range(self, value, folded):
        """`to_long_hex_number` is for ids that are DERIVED rather than drawn —
        Node's `{#cell:paraId}` FNV fallback is the caller. Clearing the high
        bit is what Word effectively does anyway."""
        assert to_long_hex_number(value) == folded
        assert is_word_readable_long_hex_number(to_long_hex_number(value))


